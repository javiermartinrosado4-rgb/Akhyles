import { Exercise, ExerciseTier, ExerciseType, Level, Muscle, Variant } from "../types";

const connectorWords = new Set([
  "a", "al", "con", "de", "del", "en", "el", "la", "las", "los", "para", "por",
]);

/** Keeps exercise labels compact and consistent across catalog, suggestions and history. */
export const formatExerciseName = (name: string) => name
  .trim()
  .split(/\s+/)
  .filter(word => !connectorWords.has(word.toLocaleLowerCase("es-ES")))
  .map(word => word.slice(0, 1).toLocaleUpperCase("es-ES") + word.slice(1))
  .join(" ");

const tierForPriority = (priority: number): ExerciseTier =>
  priority < 2 ? "S+" : priority < 3 ? "S" : priority < 4 ? "A" : "B";
function e(
  id: string,
  name: string,
  muscle: Muscle,
  priority: number,
  minLevel: Level = "beginner",
  type: ExerciseType = "isolation",
  variant: Variant = "machine",
  secondary: Muscle[] = [],
  note?: string,
): Exercise {
  const formattedName = formatExerciseName(name);
  return {
    id,
    name: formattedName,
    muscle,
    priority,
    tier: tierForPriority(priority),
    minLevel,
    type,
    variant,
    secondary,
    equipment: {
      machine: "Máquina específica",
      free: "Barra o mancuernas",
      bodyweight: "Peso corporal",
      cable: "Polea ajustable",
      smith: "Multipower",
    }[variant],
    range: type === "compound" ? [6, 8] : [8, 10],
    substitutions: [],
    note,
    pullPattern: muscle === "back"
      ? (id.includes("row") || id.includes("face-pull") ? "horizontal" : id.includes("pulldown") || id.includes("pullup") || id.includes("pullover") ? "vertical" : undefined)
      : undefined,
    scoreEligible: variant === "free" || variant === "bodyweight",
    // Total load increment for bars; per-dumbbell increment for dumbbells.
    loadStep: variant === "free" && !formattedName.toLocaleLowerCase("es-ES").includes("mancuernas") ? 2.5 : 1.25,
  };
}
